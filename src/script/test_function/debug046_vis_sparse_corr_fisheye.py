from __future__ import annotations

import argparse
import sys
from pathlib import Path

import cv2

SRC_ROOT = Path(__file__).resolve().parents[2]
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from lib_pano.correspondence.sparse_corr_io import list_corr_npz_files, load_corr_npz
from lib_pano.correspondence.sparse_corr_vis import (
    CAM2_COLOR,
    CAM4_COLOR,
    draw_corr_side_by_side,
    draw_points_canvas,
    draw_points_on_bg,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Visualize fisheye sparse correspondences generated by debug045."
    )
    parser.add_argument("--corr_dir", type=str, required=True)
    parser.add_argument("--output_dir", type=str, required=True)
    parser.add_argument("--start_frame", type=int, default=None)
    parser.add_argument("--end_frame", type=int, default=None)
    parser.add_argument("--fisheye_width", type=int, default=2880)
    parser.add_argument("--fisheye_height", type=int, default=2880)
    parser.add_argument("--max_lines", type=int, default=300)
    parser.add_argument("--sample_mode", choices=("uniform", "random"), default="uniform")
    parser.add_argument("--seed", type=int, default=1234)
    parser.add_argument("--point_radius", type=int, default=2)
    parser.add_argument("--line_thickness", type=int, default=1)
    parser.add_argument("--vis_scale", type=float, default=1.0)
    parser.add_argument("--bg_dir", type=str, default=None)
    return parser.parse_args()


def find_bg_image(bg_dir: Path, cam_id: str, frame_idx: int) -> Path | None:
    for suffix in (".jpg", ".png", ".jpeg", ".bmp"):
        path = bg_dir / cam_id / f"{frame_idx:05d}{suffix}"
        if path.exists():
            return path
    return None


def load_bg_image(
    bg_dir: str | Path | None,
    cam_id: str,
    frame_idx: int,
    width: int,
    height: int,
) -> np.ndarray | None:
    if bg_dir is None:
        return None

    bg_path = find_bg_image(Path(bg_dir), cam_id, frame_idx)
    if bg_path is None:
        return None

    bg = cv2.imread(str(bg_path), cv2.IMREAD_COLOR)
    if bg is None:
        return None
    if bg.shape[1] != width or bg.shape[0] != height:
        bg = cv2.resize(bg, (width, height), interpolation=cv2.INTER_AREA)
    return bg


def process_frame(npz_path: Path, output_dir: Path, args: argparse.Namespace) -> None:
    corr_data = load_corr_npz(
        npz_path,
        fallback_width=args.fisheye_width,
        fallback_height=args.fisheye_height,
        domain="fisheye",
    )
    frame_idx = corr_data["frame_idx"]
    width = corr_data["image_width"]
    height = corr_data["image_height"]
    pairs = corr_data["pairs"]
    frame_key = f"{frame_idx:05d}"

    cv2.imwrite(
        str(output_dir / "fisheye_points" / "cam2" / f"{frame_key}.png"),
        draw_points_canvas(pairs[:, 0:2], width, height, args.vis_scale, args.point_radius, CAM2_COLOR),
    )
    cv2.imwrite(
        str(output_dir / "fisheye_points" / "cam4" / f"{frame_key}.png"),
        draw_points_canvas(pairs[:, 2:4], width, height, args.vis_scale, args.point_radius, CAM4_COLOR),
    )
    cv2.imwrite(
        str(output_dir / "fisheye_pair_lines" / f"{frame_key}.png"),
        draw_corr_side_by_side(
            pairs,
            width,
            height,
            args.vis_scale,
            args.point_radius,
            args.line_thickness,
            args.max_lines,
            args.sample_mode,
            args.seed,
        ),
    )

    if args.bg_dir:
        bg_cam2 = load_bg_image(args.bg_dir, "cam2", frame_idx, width, height)
        if bg_cam2 is not None:
            cv2.imwrite(
                str(output_dir / "fisheye_points_bg" / "cam2" / f"{frame_key}.png"),
                draw_points_on_bg(pairs[:, 0:2], bg_cam2, width, height, args.vis_scale, args.point_radius, CAM2_COLOR),
            )

        bg_cam4 = load_bg_image(args.bg_dir, "cam4", frame_idx, width, height)
        if bg_cam4 is not None:
            cv2.imwrite(
                str(output_dir / "fisheye_points_bg" / "cam4" / f"{frame_key}.png"),
                draw_points_on_bg(pairs[:, 2:4], bg_cam4, width, height, args.vis_scale, args.point_radius, CAM4_COLOR),
            )


def main() -> None:
    args = parse_args()
    corr_dir = Path(args.corr_dir)
    output_dir = Path(args.output_dir)

    (output_dir / "fisheye_points" / "cam2").mkdir(parents=True, exist_ok=True)
    (output_dir / "fisheye_points" / "cam4").mkdir(parents=True, exist_ok=True)
    (output_dir / "fisheye_pair_lines").mkdir(parents=True, exist_ok=True)
    if args.bg_dir is not None:
        (output_dir / "fisheye_points_bg" / "cam2").mkdir(parents=True, exist_ok=True)
        (output_dir / "fisheye_points_bg" / "cam4").mkdir(parents=True, exist_ok=True)

    for npz_path in list_corr_npz_files(corr_dir, domain="fisheye", start_frame=args.start_frame, end_frame=args.end_frame):
        process_frame(npz_path, output_dir, args)
        frame_key = f"{load_corr_npz(npz_path, domain='fisheye')['frame_idx']:05d}"
        print(f"[frame {frame_key}] saved")


if __name__ == "__main__":
    main()

