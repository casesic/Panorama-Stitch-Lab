from __future__ import annotations

import argparse
import re
from pathlib import Path

import cv2
import numpy as np


CAM2_COLOR = (0, 255, 0)
CAM4_COLOR = (0, 255, 255)
LINE_COLOR = (220, 220, 220)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Visualize ERP sparse correspondences generated by debug045."
    )
    parser.add_argument("--corr_dir", type=str, required=True)
    parser.add_argument("--output_dir", type=str, required=True)
    parser.add_argument("--start_frame", type=int, default=None)
    parser.add_argument("--end_frame", type=int, default=None)
    parser.add_argument("--erp_width", type=int, default=5760)
    parser.add_argument("--erp_height", type=int, default=2880)
    parser.add_argument("--max_lines", type=int, default=300)
    parser.add_argument("--sample_mode", choices=("uniform", "random"), default="uniform")
    parser.add_argument("--seed", type=int, default=1234)
    parser.add_argument("--point_radius", type=int, default=2)
    parser.add_argument("--line_thickness", type=int, default=1)
    parser.add_argument("--vis_scale", type=float, default=1.0)
    parser.add_argument("--bg_dir", type=str, default=None)
    return parser.parse_args()


def make_scaled_shape(width: int, height: int, vis_scale: float) -> tuple[int, int]:
    return max(1, int(round(width * vis_scale))), max(1, int(round(height * vis_scale)))


def points_in_bounds(pts: np.ndarray, width: int, height: int) -> np.ndarray:
    finite = np.isfinite(pts).all(axis=1)
    return (
        finite
        & (pts[:, 0] >= 0)
        & (pts[:, 0] < width)
        & (pts[:, 1] >= 0)
        & (pts[:, 1] < height)
    )


def sample_line_indices(num_pairs: int, max_lines: int, sample_mode: str, seed: int) -> np.ndarray:
    if max_lines <= 0 or num_pairs == 0:
        return np.empty((0,), dtype=np.int64)
    if num_pairs <= max_lines:
        return np.arange(num_pairs, dtype=np.int64)
    if sample_mode == "uniform":
        return np.linspace(0, num_pairs - 1, max_lines, dtype=np.int64)

    rng = np.random.default_rng(seed)
    sampled = rng.choice(num_pairs, size=max_lines, replace=False)
    sampled.sort()
    return sampled.astype(np.int64, copy=False)


def draw_points_canvas(
    pts: np.ndarray,
    width: int,
    height: int,
    vis_scale: float,
    point_radius: int,
    color: tuple[int, int, int],
) -> np.ndarray:
    scaled_w, scaled_h = make_scaled_shape(width, height, vis_scale)
    canvas = np.zeros((scaled_h, scaled_w, 3), dtype=np.uint8)
    valid_pts = pts[points_in_bounds(pts, width, height)]
    radius = max(1, int(round(point_radius * vis_scale)))

    draw_pts = np.rint(valid_pts * vis_scale).astype(np.int32)
    for x, y in draw_pts:
        if 0 <= x < scaled_w and 0 <= y < scaled_h:
            cv2.circle(canvas, (int(x), int(y)), radius, color, -1, lineType=cv2.LINE_AA)
    return canvas


def draw_erp_overlay_canvas(
    pairs: np.ndarray,
    width: int,
    height: int,
    vis_scale: float,
    point_radius: int,
    line_thickness: int,
    max_lines: int,
    sample_mode: str,
    seed: int,
) -> np.ndarray:
    scaled_w, scaled_h = make_scaled_shape(width, height, vis_scale)
    canvas = np.zeros((scaled_h, scaled_w, 3), dtype=np.uint8)

    cam2_pts = pairs[:, 0:2]
    cam4_pts = pairs[:, 2:4]
    valid_cam2 = points_in_bounds(cam2_pts, width, height)
    valid_cam4 = points_in_bounds(cam4_pts, width, height)

    radius = max(1, int(round(point_radius * vis_scale)))
    thickness = max(1, int(round(line_thickness * vis_scale)))

    cam2_draw = np.rint(cam2_pts[valid_cam2] * vis_scale).astype(np.int32)
    for x, y in cam2_draw:
        if 0 <= x < scaled_w and 0 <= y < scaled_h:
            cv2.circle(canvas, (int(x), int(y)), radius, CAM2_COLOR, -1, lineType=cv2.LINE_AA)

    cam4_draw = np.rint(cam4_pts[valid_cam4] * vis_scale).astype(np.int32)
    for x, y in cam4_draw:
        if 0 <= x < scaled_w and 0 <= y < scaled_h:
            cv2.circle(canvas, (int(x), int(y)), radius, CAM4_COLOR, -1, lineType=cv2.LINE_AA)

    for row_idx in sample_line_indices(len(pairs), max_lines, sample_mode, seed):
        if not (valid_cam2[row_idx] and valid_cam4[row_idx]):
            continue

        p2 = cam2_pts[row_idx]
        p4 = cam4_pts[row_idx]
        p2_draw = (int(round(p2[0] * vis_scale)), int(round(p2[1] * vis_scale)))
        p4_draw = (int(round(p4[0] * vis_scale)), int(round(p4[1] * vis_scale)))
        cv2.line(canvas, p2_draw, p4_draw, LINE_COLOR, thickness, lineType=cv2.LINE_AA)
        cv2.circle(canvas, p2_draw, radius, CAM2_COLOR, -1, lineType=cv2.LINE_AA)
        cv2.circle(canvas, p4_draw, radius, CAM4_COLOR, -1, lineType=cv2.LINE_AA)

    return canvas


def find_bg_image(bg_dir: Path, cam_id: str, frame_idx: int) -> Path | None:
    for suffix in (".jpg", ".png", ".jpeg", ".bmp"):
        path = bg_dir / cam_id / f"{frame_idx:05d}{suffix}"
        if path.exists():
            return path
    return None


def load_bg_image(
    bg_dir: str | Path | None,
    cam_id: str,
    frame_idx: int,
    width: int,
    height: int,
) -> np.ndarray | None:
    if bg_dir is None:
        return None

    bg_path = find_bg_image(Path(bg_dir), cam_id, frame_idx)
    if bg_path is None:
        return None

    bg = cv2.imread(str(bg_path), cv2.IMREAD_COLOR)
    if bg is None:
        return None
    if bg.shape[1] != width or bg.shape[0] != height:
        bg = cv2.resize(bg, (width, height), interpolation=cv2.INTER_AREA)
    return bg


def draw_points_on_bg(
    pts: np.ndarray,
    bg: np.ndarray,
    width: int,
    height: int,
    vis_scale: float,
    point_radius: int,
    color: tuple[int, int, int],
) -> np.ndarray:
    scaled_w, scaled_h = make_scaled_shape(width, height, vis_scale)
    canvas = cv2.resize(bg, (scaled_w, scaled_h), interpolation=cv2.INTER_AREA) if vis_scale != 1.0 else bg.copy()
    valid_pts = pts[points_in_bounds(pts, width, height)]
    radius = max(1, int(round(point_radius * vis_scale)))

    draw_pts = np.rint(valid_pts * vis_scale).astype(np.int32)
    for x, y in draw_pts:
        if 0 <= x < scaled_w and 0 <= y < scaled_h:
            cv2.circle(canvas, (int(x), int(y)), radius, color, -1, lineType=cv2.LINE_AA)
    return canvas


def _npz_scalar(value: np.ndarray) -> object:
    arr = np.asarray(value)
    return arr.item() if arr.shape == () else arr.tolist()


def load_corr_npz(path: Path, fallback_width: int, fallback_height: int) -> tuple[int, int, int, np.ndarray]:
    with np.load(path, allow_pickle=False) as data:
        pairs = data["pairs"].astype(np.float32)
        width = int(_npz_scalar(data["image_width"])) if "image_width" in data.files else int(fallback_width)
        height = int(_npz_scalar(data["image_height"])) if "image_height" in data.files else int(fallback_height)
        if "frame_idx" in data.files:
            frame_idx = int(_npz_scalar(data["frame_idx"]))
        else:
            frame_idx = int(re.match(r"^(\d+)_erp_corr\.npz$", path.name).group(1))
    return frame_idx, width, height, pairs


def discover_corr_files(corr_dir: Path, start_frame: int | None, end_frame: int | None) -> list[Path]:
    input_dir = corr_dir / "erp_corr"
    pattern = re.compile(r"^(\d+)_erp_corr\.npz$")
    paths: list[tuple[int, Path]] = []
    for path in input_dir.glob("*_erp_corr.npz"):
        match = pattern.match(path.name)
        if match is None:
            continue
        frame_idx = int(match.group(1))
        if start_frame is not None and frame_idx < start_frame:
            continue
        if end_frame is not None and frame_idx > end_frame:
            continue
        paths.append((frame_idx, path))
    return [path for _, path in sorted(paths)]


def process_frame(npz_path: Path, output_dir: Path, args: argparse.Namespace) -> None:
    frame_idx, width, height, pairs = load_corr_npz(npz_path, args.erp_width, args.erp_height)
    frame_key = f"{frame_idx:05d}"

    cv2.imwrite(
        str(output_dir / "erp_points" / "cam2" / f"{frame_key}.png"),
        draw_points_canvas(pairs[:, 0:2], width, height, args.vis_scale, args.point_radius, CAM2_COLOR),
    )
    cv2.imwrite(
        str(output_dir / "erp_points" / "cam4" / f"{frame_key}.png"),
        draw_points_canvas(pairs[:, 2:4], width, height, args.vis_scale, args.point_radius, CAM4_COLOR),
    )
    cv2.imwrite(
        str(output_dir / "erp_overlay_lines" / f"{frame_key}.png"),
        draw_erp_overlay_canvas(
            pairs,
            width,
            height,
            args.vis_scale,
            args.point_radius,
            args.line_thickness,
            args.max_lines,
            args.sample_mode,
            args.seed,
        ),
    )

    if args.bg_dir:
        bg_cam2 = load_bg_image(args.bg_dir, "cam2", frame_idx, width, height)
        if bg_cam2 is not None:
            cv2.imwrite(
                str(output_dir / "erp_points_bg" / "cam2" / f"{frame_key}.png"),
                draw_points_on_bg(pairs[:, 0:2], bg_cam2, width, height, args.vis_scale, args.point_radius, CAM2_COLOR),
            )

        bg_cam4 = load_bg_image(args.bg_dir, "cam4", frame_idx, width, height)
        if bg_cam4 is not None:
            cv2.imwrite(
                str(output_dir / "erp_points_bg" / "cam4" / f"{frame_key}.png"),
                draw_points_on_bg(pairs[:, 2:4], bg_cam4, width, height, args.vis_scale, args.point_radius, CAM4_COLOR),
            )


def main() -> None:
    args = parse_args()
    corr_dir = Path(args.corr_dir)
    output_dir = Path(args.output_dir)

    (output_dir / "erp_points" / "cam2").mkdir(parents=True, exist_ok=True)
    (output_dir / "erp_points" / "cam4").mkdir(parents=True, exist_ok=True)
    (output_dir / "erp_overlay_lines").mkdir(parents=True, exist_ok=True)
    if args.bg_dir is not None:
        (output_dir / "erp_points_bg" / "cam2").mkdir(parents=True, exist_ok=True)
        (output_dir / "erp_points_bg" / "cam4").mkdir(parents=True, exist_ok=True)

    for npz_path in discover_corr_files(corr_dir, args.start_frame, args.end_frame):
        process_frame(npz_path, output_dir, args)
        frame_match = re.match(r"^(\d+)_erp_corr\.npz$", npz_path.name)
        frame_key = f"{int(frame_match.group(1)):05d}" if frame_match is not None else npz_path.stem
        print(f"[frame {frame_key}] saved")


if __name__ == "__main__":
    main()

